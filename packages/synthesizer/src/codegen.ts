import type { ArgConstraint, PolicySpec, Recording, ScValue } from "@warden/core";
import { explainPolicy } from "@warden/core";
import { generateCases, type Case } from "./denygen.js";

/**
 * PolicySpec → Rust. Fully deterministic: same spec + recording in, same bytes out.
 * No model output ever reaches this stage — the spec was schema-validated upstream.
 *
 * Emits a standalone crate (detached from any parent cargo workspace) so the
 * harness can `cargo test --manifest-path <dir>/Cargo.toml` in isolation:
 *
 *   Cargo.toml
 *   src/lib.rs             pub fn enforce(&Env, &Context, &mut Counters) -> Result<(), Symbol>
 *   tests/permit_deny.rs   generated permit + deny cases (+ window sequence tests)
 *   POLICY.md              human-readable contract, from the same source as the code
 */

export interface GeneratedCrate {
  crateName: string;
  files: Record<string, string>;
  cases: Case[];
  skipped: string[];
}

const WINDOW_SECONDS: Record<string, number> = {
  "per-call": 0,
  hour: 3600,
  day: 86400,
  week: 604800,
  month: 2592000,
};

export interface CodegenOptions {
  /** Relative path from the generated crate dir to the policy-core crate. */
  policyCorePath?: string;
  sorobanSdkVersion?: string;
}

export function generateCrate(spec: PolicySpec, recording: Recording, opts: CodegenOptions = {}): GeneratedCrate {
  const crateName = `warden_policy_${recording.id.replace(/[^a-z0-9]/g, "_")}`;
  const policyCorePath = opts.policyCorePath ?? "../../policy-core";
  const sdkVersion = opts.sorobanSdkVersion ?? "27.0.0";
  const cases = generateCases(recording, spec);
  const skipped: string[] = [];

  const files: Record<string, string> = {
    "Cargo.toml": cargoToml(crateName, policyCorePath, sdkVersion),
    "src/lib.rs": libRs(spec, crateName),
    "tests/permit_deny.rs": testsRs(spec, crateName, cases, skipped),
    "POLICY.md": policyMd(spec, cases, skipped),
  };
  return { crateName, files, cases, skipped };
}

function cargoToml(crateName: string, policyCorePath: string, sdkVersion: string): string {
  return `# generated by @warden/synthesizer — do not edit by hand
[package]
name = "${crateName}"
version = "0.1.0"
edition = "2021"
publish = false

# standalone: detach from any parent cargo workspace
[workspace]

[lib]
crate-type = ["rlib"]

[dependencies]
soroban-sdk = { version = "${sdkVersion}" }
policy-core = { path = "${policyCorePath}", package = "warden-policy-core" }

[dev-dependencies]
soroban-sdk = { version = "${sdkVersion}", features = ["testutils"] }
`;
}

