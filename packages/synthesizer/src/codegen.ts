function testsRs(spec: PolicySpec, crateName: string, cases: Case[], skipped: string[]): string {
  const tests: string[] = [];
  for (const c of cases) {
    if (c.invocation.args.some((a) => a.kind === "opaque")) {
      skipped.push(`${c.name}: contains opaque args that cannot be reconstructed in tests`);
      continue;
    }
    tests.push(caseTest(c));
  }
  tests.push(...windowSequenceTests(spec, cases));

  return `// generated by @warden/synthesizer — do not edit by hand
#![cfg(test)]

use ${crateName}::enforce;
use policy_core::Counters;
use soroban_sdk::auth::{Context, ContractContext};
use soroban_sdk::testutils::Ledger;
#[allow(unused_imports)]
use soroban_sdk::{vec, Address, Bytes, Env, IntoVal, String as SorString, Symbol, Val, Vec};

fn ctx(env: &Env, contract: &str, function: &str, args: Vec<Val>) -> Context {
    Context::Contract(ContractContext {
        contract: Address::from_str(env, contract),
        fn_name: Symbol::new(env, function),
        args,
    })
}

fn fresh(env: &Env) -> Counters {
    env.ledger().with_mut(|li| li.timestamp = 1_000_000);
    Counters::new(env)
}

${tests.join("\n\n")}
`;
}

function caseTest(c: Case): string {
  const args = c.invocation.args.map((a) => testValue(a)).join(", ");
  const assertion =
    c.expect === "permit"
      ? `assert_eq!(enforce(&env, &c, &mut counters), Ok(()), "expected PERMIT: ${c.reason}");`
      : `assert!(enforce(&env, &c, &mut counters).is_err(), "expected DENY: ${c.reason}");`;
  return `#[test]
fn ${c.name}() {
    let env = Env::default();
    let mut counters = fresh(&env);
    let c = ctx(&env, "${c.invocation.contract}", "${escapeRust(c.invocation.function)}", vec![&env${args ? `, ${args}` : ""}]);
    ${assertion}
}`;
}

/** For the first cappedSum rule: prove the window counter accumulates and resets. */
function windowSequenceTests(spec: PolicySpec, cases: Case[]): string[] {
  for (const rule of spec.rules) {
    const capped = rule.args.find((a) => a.kind === "cappedSum");
    if (!capped || capped.kind !== "cappedSum") continue;
    const winSecs = WINDOW_SECONDS[capped.window] ?? 0;
    if (winSecs === 0) continue;
    const permit = cases.find(
      (c) =>
        c.expect === "permit" &&
        c.invocation.contract === rule.contract &&
        c.invocation.function === rule.function &&
        !c.invocation.args.some((a) => a.kind === "opaque"),
    );
    if (!permit) continue;
    const amount = permit.invocation.args[capped.argIndex];
    if (!amount || amount.kind !== "i128") continue;
    if (BigInt(amount.value) * 2n <= BigInt(capped.cap)) continue; // sequence wouldn't exceed cap
    const args = permit.invocation.args.map((a) => testValue(a)).join(", ");
    return [
      `#[test]
fn deny_${rule.id}_window_accumulates() {
    let env = Env::default();
    let mut counters = fresh(&env);
    let mk = || ctx(&env, "${permit.invocation.contract}", "${escapeRust(permit.invocation.function)}", vec![&env, ${args}]);
    assert_eq!(enforce(&env, &mk(), &mut counters), Ok(()), "first call within cap");
    assert!(enforce(&env, &mk(), &mut counters).is_err(), "second call must exceed the rolling cap");
}`,
      `#[test]
fn permit_${rule.id}_window_resets() {
    let env = Env::default();
    let mut counters = fresh(&env);
    let mk = || ctx(&env, "${permit.invocation.contract}", "${escapeRust(permit.invocation.function)}", vec![&env, ${args}]);
    assert_eq!(enforce(&env, &mk(), &mut counters), Ok(()));
    env.ledger().with_mut(|li| li.timestamp += ${winSecs}u64 + 1);
    assert_eq!(enforce(&env, &mk(), &mut counters), Ok(()), "counter must reset after the window elapses");
}`,
    ];
  }
  return [];
}

/** Rust expression producing a Val for tests (env in scope as &env). */
function testValue(v: ScValue): string {
  switch (v.kind) {
    case "address":
      return `Address::from_str(&env, "${v.value}").into_val(&env)`;
    case "i128":
      return `(${v.value}i128).into_val(&env)`;
    case "u64":
      return `(${v.value}u64).into_val(&env)`;
    case "u32":
      return `(${v.value}u32).into_val(&env)`;
    case "symbol":
      return `Symbol::new(&env, "${escapeRust(v.value)}").into_val(&env)`;
    case "string":
      return `SorString::from_str(&env, "${escapeRust(v.value)}").into_val(&env)`;
    case "bool":
      return `${v.value}.into_val(&env)`;
    case "bytes":
      return `Bytes::from_slice(&env, &[${hexToByteList(v.value)}]).into_val(&env)`;
    case "opaque":
      throw new CodegenError("unreachable: opaque cases are skipped");
  }
}

function policyMd(spec: PolicySpec, cases: Case[], skipped: string[]): string {
  const rows = cases.map((c) => `| ${c.name} | ${c.expect} | ${c.reason} |`).join("\n");
  const skippedNote = skipped.length
    ? `\n## Skipped cases\n${skipped.map((s) => `- ${s}`).join("\n")}\n`
    : "";
  return `# Generated policy

\`\`\`
${explainPolicy(spec)}
\`\`\`

## Verification matrix

| case | expectation | reason |
|---|---|---|
${rows}
${skippedNote}
Generated by @warden/synthesizer. The Rust in \`src/lib.rs\` and this document are rendered from the same PolicySpec — if they disagree, the spec is the truth and both are regenerated.
`;
}

function symbolExpr(s: string): string {
  return s.length <= 9 && /^[A-Za-z0-9_]+$/.test(s)
    ? `symbol_short!("${s}")`
    : `Symbol::new(env, "${escapeRust(s)}")`;
}

function escapeRust(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function hexToByteList(hex: string): string {
  const bytes: string[] = [];
  for (let i = 0; i < hex.length; i += 2) bytes.push(`0x${hex.slice(i, i + 2)}`);
  return bytes.join(", ");
}

export class CodegenError extends Error {
  constructor(msg: string) {
    super(msg);
    this.name = "CodegenError";
  }
}
