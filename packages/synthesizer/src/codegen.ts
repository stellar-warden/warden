function libRs(spec: PolicySpec, crateName: string): string {
  const addrTable = buildAddressTable(spec);
  const ruleBlocks = spec.rules.map((r) => ruleBlock(r, addrTable)).join("\n");
  const addrFns = [...addrTable.entries()]
    .map(([strkey, fn]) => `fn ${fn}(env: &Env) -> Address { Address::from_str(env, "${strkey}") }`)
    .join("\n");

  return `//! ${crateName} — generated by @warden/synthesizer. DO NOT EDIT BY HAND.
//!
${explainPolicy(spec)
  .split("\n")
  .map((l) => `//! ${l}`)
  .join("\n")}
#![no_std]

use policy_core::{arg_address, arg_bool, arg_bytes, arg_i128, arg_string, arg_symbol, arg_u32, arg_u64, Counters};
use soroban_sdk::{auth::Context, symbol_short, Address, Env, Symbol};
#[allow(unused_imports)]
use soroban_sdk::{Bytes, String as SorString};

${addrFns}

/// Deny-by-default enforcement over a single authorized invocation context.
/// Returns Ok(()) iff the context matches one of the synthesized rules AND
/// every argument constraint (including rolling caps) holds.
pub fn enforce(env: &Env, ctx: &Context, counters: &mut Counters) -> Result<(), Symbol> {
    let cc = match ctx {
        Context::Contract(cc) => cc,
        _ => return Err(symbol_short!("noctx")),
    };
${ruleBlocks}
    Err(symbol_short!("norule"))
}
`;
}

function buildAddressTable(spec: PolicySpec): Map<string, string> {
  const table = new Map<string, string>();
  const add = (strkey: string) => {
    if (!table.has(strkey)) table.set(strkey, `addr_${table.size + 1}`);
  };
  for (const r of spec.rules) {
    add(r.contract);
    for (const c of r.args) {
      if (c.kind === "exact" && c.value.kind === "address") add(c.value.value);
      if (c.kind === "anyOf") for (const v of c.values) if (v.kind === "address") add(v.value);
    }
  }
  return table;
}

function ruleBlock(rule: PolicySpec["rules"][number], addrs: Map<string, string>): string {
  const checks = rule.args
    .filter((c) => c.kind !== "any")
    .map((c) => constraintCheck(rule.id, c, addrs))
    .join("\n");
  return `    // rule ${rule.id}: ${rule.contract.slice(0, 8)}…::${rule.function}
    if cc.contract == ${addrs.get(rule.contract)}(env) && cc.fn_name == ${symbolExpr(rule.function)} {
        if cc.args.len() != ${rule.argCount}u32 {
            return Err(symbol_short!("argcnt"));
        }
${checks}
        return Ok(());
    }`;
}

function constraintCheck(ruleId: string, c: ArgConstraint, addrs: Map<string, string>): string {
  switch (c.kind) {
    case "exact":
      return matchCheck(c.argIndex, [c.value], addrs, "exact value");
    case "anyOf":
      return matchCheck(c.argIndex, c.values, addrs, "allowlist");
    case "cappedSum": {
      const winSecs = WINDOW_SECONDS[c.window] ?? 0;
      return `        {
            // arg${c.argIndex}: rolling cap ${c.cap} per ${c.window}
            let amt = arg_i128(env, &cc.args, ${c.argIndex}).ok_or(symbol_short!("argtype"))?;
            if amt < 0 {
                return Err(symbol_short!("neg"));
            }
            if !counters.add_checked(env, ${symbolExpr(ruleId)}, ${c.argIndex}u32, ${winSecs}u64, amt, ${c.cap}i128) {
                return Err(symbol_short!("cap"));
            }
        }`;
    }
    case "any":
      return "";
  }
}

function matchCheck(argIndex: number, values: ScValue[], addrs: Map<string, string>, label: string): string {
  const kind = values[0]!.kind;
  const { getter, cmp } = accessor(kind);
  const conditions = values.map((v) => cmp(rustValue(v, addrs))).join(" || ");
  return `        {
            // arg${argIndex}: ${label} (${kind})
            let v = ${getter}(env, &cc.args, ${argIndex}).ok_or(symbol_short!("argtype"))?;
            if !(${conditions}) {
                return Err(symbol_short!("nomatch"));
            }
        }`;
}

function accessor(kind: ScValue["kind"]): { getter: string; cmp: (expr: string) => string } {
  switch (kind) {
    case "address":
      return { getter: "arg_address", cmp: (e) => `v == ${e}` };
    case "i128":
      return { getter: "arg_i128", cmp: (e) => `v == ${e}` };
    case "u64":
      return { getter: "arg_u64", cmp: (e) => `v == ${e}` };
    case "u32":
      return { getter: "arg_u32", cmp: (e) => `v == ${e}` };
    case "symbol":
      return { getter: "arg_symbol", cmp: (e) => `v == ${e}` };
    case "string":
      return { getter: "arg_string", cmp: (e) => `v == ${e}` };
    case "bool":
      return { getter: "arg_bool", cmp: (e) => `v == ${e}` };
    case "bytes":
      return { getter: "arg_bytes", cmp: (e) => `v == ${e}` };
    default:
      throw new CodegenError(`cannot generate a matcher for '${kind}' values — refine the spec`);
  }
}

/** Rust expression for a value in enforcement context (env in scope). */
function rustValue(v: ScValue, addrs: Map<string, string>): string {
  switch (v.kind) {
    case "address": {
      const fn = addrs.get(v.value);
      return fn ? `${fn}(env)` : `Address::from_str(env, "${v.value}")`;
    }
    case "i128":
      return `${v.value}i128`;
    case "u64":
      return `${v.value}u64`;
    case "u32":
      return `${v.value}u32`;
    case "symbol":
      return symbolExpr(v.value);
    case "string":
      return `SorString::from_str(env, "${escapeRust(v.value)}")`;
    case "bool":
      return String(v.value);
    case "bytes":
      return `Bytes::from_slice(env, &[${hexToByteList(v.value)}])`;
    case "opaque":
      throw new CodegenError("opaque values cannot be matched — constraint should have been 'any'");
  }
}

